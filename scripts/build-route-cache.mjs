/* Pre-cache OSRM road routes for the stop orders the demo actually uses.
 *
 * ⚠⚠ Run this on a good connection, commit the output, and the demo never waits
 * on router.project-osrm.org again. The public demo server is rate-limited and
 * is the wrong thing to have between a director and a spinner. Live routing
 * stays enabled for orders a planner invents in the room — this only removes the
 * dependency for the scripted ones.
 *
 *   node scripts/build-route-cache.mjs
 *
 * Output: lib/routes-cache.ts
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const DEPOT = { lat: -17.877, lng: 31.005 };
const SUB = {
  Waterfalls: [-17.888, 31.025], Mabvuku: [-17.82, 31.18], Borrowdale: [-17.75, 31.1],
  Chitungwiza: [-17.993, 31.075], Greendale: [-17.81, 31.13], Kuwadzana: [-17.83, 30.92],
  Avondale: [-17.799, 31.035], Hatfield: [-17.862, 31.11], Highfield: [-17.877, 30.99],
  Newlands: [-17.806, 31.073], Msasa: [-17.846, 31.123], Eastlea: [-17.828, 31.07],
  Braeside: [-17.846, 31.062], Hillside: [-17.86, 31.09], Cranborne: [-17.86, 31.008],
};
const co = (s) => SUB[s] || [-17.84, 31.05];

const SEED = ['Greendale', 'Greendale', 'Newlands', 'Eastlea', 'Msasa', 'Braeside', 'Hillside', 'Cranborne', 'Waterfalls'];
const POOL = ['Greendale', 'Avondale', 'Newlands', 'Msasa', 'Eastlea', 'Braeside', 'Hillside', 'Hatfield', 'Cranborne', 'Waterfalls'];

function haversineKm(a, b) {
  const R = 6371;
  const dLat = ((b[0] - a[0]) * Math.PI) / 180, dLng = ((b[1] - a[1]) * Math.PI) / 180;
  const la = (a[0] * Math.PI) / 180, lb = (b[0] * Math.PI) / 180;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(la) * Math.cos(lb) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h)) * 1.35;
}

function nearestNeighbour(list) {
  const rest = list.slice(), out = [];
  let cur = [DEPOT.lat, DEPOT.lng];
  while (rest.length) {
    let bi = 0, bd = Infinity;
    rest.forEach((s, i) => { const d = haversineKm(cur, co(s)); if (d < bd) { bd = d; bi = i; } });
    const p = rest.splice(bi, 1)[0];
    out.push(p); cur = co(p);
  }
  return out;
}

/* Every order the scripted demo can reach in one click from the seeded trip:
   the planner's order, the suggestion, each single removal, and each single
   addition from the pool — plus the same for the accepted suggestion. */
const orders = new Map();
const add = (list) => { if (list.length) orders.set(list.join('>'), list); };

const suggested = nearestNeighbour(SEED);
add(SEED);
add(suggested);
for (const base of [SEED, suggested]) {
  base.forEach((_, i) => add(base.filter((__, j) => j !== i)));
  // Every pool row can be added, including one in a suburb already on the trip —
  // the order key is the suburb sequence, so that is a distinct route.
  POOL.forEach((p) => add(base.concat([p])));
  // an added stop also changes what the optimiser would suggest
  POOL.forEach((p) => add(nearestNeighbour(base.concat([p]))));
}

const url = (list) => {
  const pts = [[DEPOT.lat, DEPOT.lng], ...list.map(co), [DEPOT.lat, DEPOT.lng]];
  return 'https://router.project-osrm.org/route/v1/driving/' +
    pts.map((p) => p[1].toFixed(5) + ',' + p[0].toFixed(5)).join(';') +
    '?overview=full&geometries=geojson';
};

const out = {};
let ok = 0, fail = 0;
const keys = [...orders.keys()];
for (const key of keys) {
  const list = orders.get(key);
  try {
    const res = await fetch(url(list));
    const j = await res.json();
    const rt = j?.routes?.[0];
    if (!rt) throw new Error('no route');
    out[key] = {
      km: +(rt.distance / 1000).toFixed(3),
      min: +(rt.duration / 60).toFixed(2),
      // Thin the geometry: full OSRM geojson is far more detail than a 560px map
      // needs, and the whole cache ships in the bundle.
      coords: rt.geometry.coordinates
        .filter((_, i, a) => i % 5 === 0 || i === a.length - 1)
        .map((c) => [+c[1].toFixed(4), +c[0].toFixed(4)]),
    };
    ok++;
  } catch (e) {
    fail++;
    console.error('MISS', key, String(e.message || e));
  }
  await new Promise((r) => setTimeout(r, 350)); // be a good citizen of a free server
}

mkdirSync(join(root, 'lib'), { recursive: true });
writeFileSync(
  join(root, 'lib', 'routes-cache.ts'),
  `/* GENERATED by scripts/build-route-cache.mjs — do not edit by hand.
 *
 * ⚠⚠ Road routes from OSRM for every stop order the scripted demo can reach in
 * one click. Shipping these means the console never waits on a rate-limited
 * public server in front of an audience. Orders not in here still route live and
 * still draw dashed until the answer lands.
 *
 * ${ok} orders cached${fail ? `, ${fail} missed (they will route live)` : ''}.
 * Geometry is thinned to every fifth vertex — enough for a 560px map.
 */

export type CachedRoute = { km: number; min: number; coords: [number, number][] };

export const CACHED_ROUTES: Record<string, CachedRoute> = ${JSON.stringify(out, null, 1)} as Record<string, CachedRoute>;
`
);
console.log(`cached ${ok}/${keys.length} orders (${fail} missed)`);
